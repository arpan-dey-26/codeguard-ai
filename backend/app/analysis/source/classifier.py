"""Deterministic file classification and language detection.

Two decisions, both made from the path and the diff metadata alone — before
any content is fetched, which is the point: deciding not to download a 4 MB
lockfile only helps if the decision precedes the download.

**Language detection is extension-based, and that is deliberate.** The brief's
"do not blindly trust file extensions" is satisfied not by sniffing content —
which would mean heuristics that differ between runs and, at worst, executing
or evaluating repository data — but by making the extension a *lookup into a
closed table* whose miss case is an explicit ``UNSUPPORTED_LANGUAGE``
classification rather than a guess. An unknown extension never becomes "probably
JavaScript"; it becomes a recorded, reportable skip. Content-based detection is
left to a later phase if evidence ever justifies it, and would still never
execute the file.

Classification order matters and is fixed: the first rule that matches wins, so
the recorded reason is always the most specific true one.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from app.analysis.diff.models import FileChangeType, PatchStatus
from app.analysis.source.models import FileClassification, SourceStatus

# -- language table ---------------------------------------------------------
# Closed, explicit, lowercase. A miss is UNSUPPORTED_LANGUAGE, never a guess.
LANGUAGE_BY_EXTENSION: dict[str, str] = {
    ".py": "python",
    ".pyi": "python",
    ".js": "javascript",
    ".jsx": "javascript",
    ".mjs": "javascript",
    ".cjs": "javascript",
    ".ts": "typescript",
    ".tsx": "typescript",
    ".mts": "typescript",
    ".cts": "typescript",
    ".java": "java",
}

SUPPORTED_LANGUAGES: frozenset[str] = frozenset(LANGUAGE_BY_EXTENSION.values())

# Extensions that are unambiguously not text we parse. Listed explicitly so a
# binary file is classified as BINARY (an accurate reason) rather than as
# "unsupported language" (a misleading one).
BINARY_EXTENSIONS: frozenset[str] = frozenset(
    {
        ".png",
        ".jpg",
        ".jpeg",
        ".gif",
        ".bmp",
        ".ico",
        ".webp",
        ".tiff",
        ".avif",
        ".pdf",
        ".zip",
        ".gz",
        ".tar",
        ".bz2",
        ".xz",
        ".7z",
        ".rar",
        ".mp3",
        ".mp4",
        ".wav",
        ".avi",
        ".mov",
        ".webm",
        ".ogg",
        ".flac",
        ".woff",
        ".woff2",
        ".ttf",
        ".otf",
        ".eot",
        ".so",
        ".dll",
        ".dylib",
        ".exe",
        ".bin",
        ".class",
        ".jar",
        ".o",
        ".a",
        ".pyc",
        ".pyo",
        ".wasm",
        ".db",
        ".sqlite",
        ".sqlite3",
    }
)

# Path segments that mark dependency trees. Matched as whole path components,
# never as substrings: a file called `my_vendor_utils.py` is source code, and a
# substring match would silently discard it.
VENDOR_DIRECTORIES: frozenset[str] = frozenset(
    {
        "node_modules",
        "vendor",
        "third_party",
        "thirdparty",
        "bower_components",
        "dist",
        "build",
        "out",
        "target",
        ".venv",
        "venv",
        "site-packages",
        "__pycache__",
        ".git",
        ".tox",
        ".mypy_cache",
        ".pytest_cache",
        "eggs",
    }
)

LOCKFILE_NAMES: frozenset[str] = frozenset(
    {
        "package-lock.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "poetry.lock",
        "pipfile.lock",
        "gemfile.lock",
        "cargo.lock",
        "composer.lock",
        "go.sum",
        "gradle.lockfile",
    }
)

GENERATED_FILENAME_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\.min\.(js|css)$"),
    re.compile(r"_pb2(_grpc)?\.pyi?$"),
    re.compile(r"\.pb\.(go|java|ts|js)$"),
    re.compile(r"\.g\.(dart|cs|ts)$"),
    re.compile(r"\.generated\.[a-z0-9]+$"),
    re.compile(r"\.d\.ts$"),
    re.compile(r"\.snap$"),
    re.compile(r"(^|/)migrations?/.*\.(sql)$"),
)

# Markers a generator writes into the first few lines of its output. Checked
# only when content is already in hand — never as a reason to fetch.
GENERATED_CONTENT_MARKERS: tuple[str, ...] = (
    "@generated",
    "do not edit",
    "автоматически",
    "code generated by",
    "this file is auto-generated",
    "autogenerated",
)
GENERATED_MARKER_SCAN_LINES = 5


@dataclass(frozen=True, slots=True)
class ClassificationLimits:
    """Size ceilings. Configuration, never magic numbers at a call site."""

    max_file_bytes: int
    max_total_bytes: int
    max_changed_lines_per_file: int


def detect_language(path: str) -> str | None:
    """Return the supported language for a path, or ``None``.

    Deterministic and total: same path, same answer, always, with no content
    read and nothing executed.
    """
    lowered = path.lower()
    # Longest extension first, so `.d.ts` is never mistaken for `.ts` and
    # `.pb.go` is matched before `.go` if that is ever added.
    for ext in sorted(LANGUAGE_BY_EXTENSION, key=len, reverse=True):
        if lowered.endswith(ext):
            return LANGUAGE_BY_EXTENSION[ext]
    return None


def _extension(path: str) -> str:
    name = path.rsplit("/", 1)[-1].lower()
    dot = name.rfind(".")
    return name[dot:] if dot > 0 else ""


def is_vendored(path: str) -> bool:
    """Whole-component match, so `my_vendor_utils.py` survives."""
    return any(part in VENDOR_DIRECTORIES for part in path.split("/")[:-1])


def is_generated_path(path: str) -> bool:
    name = path.rsplit("/", 1)[-1].lower()
    if name in LOCKFILE_NAMES:
        return True
    return any(p.search(path.lower()) for p in GENERATED_FILENAME_PATTERNS)


def has_generated_marker(text: str) -> bool:
    """Scan only the first few lines, and only content we already hold."""
    head = "\n".join(text.split("\n")[:GENERATED_MARKER_SCAN_LINES]).lower()
    return any(marker in head for marker in GENERATED_CONTENT_MARKERS)


def classify(
    *,
    path: str,
    change_type: FileChangeType,
    patch_status: PatchStatus,
    changed_line_count: int,
    limits: ClassificationLimits,
    declared_size_bytes: int | None = None,
) -> FileClassification:
    """Decide whether a file should be fetched and parsed.

    First match wins, so the recorded reason is the most specific true one.
    The order encodes what a user most needs to know: "it was deleted" is more
    useful than "it has no patch", which is more useful than "unsupported".
    """
    language = detect_language(path)

    def verdict(status: SourceStatus, reason: str | None = None) -> FileClassification:
        return FileClassification(path=path, language=language, status=status, reason=reason)

    # 1. A deleted file has no head version. Nothing downstream may ask for one.
    if change_type is FileChangeType.DELETED:
        return verdict(SourceStatus.DELETED, "File was removed by this pull request.")

    # 2. Binary, by extension or by GitHub's own signal (an absent patch marked
    #    binary). Reported as binary, not as "unsupported language".
    if _extension(path) in BINARY_EXTENSIONS or patch_status is PatchStatus.ABSENT_BINARY:
        return verdict(SourceStatus.BINARY, "Binary file; not parsed as source.")

    # 3. Dependency trees and generated output: real files, but not the
    #    author's work, so reviewing them is noise.
    if is_vendored(path):
        return verdict(SourceStatus.VENDORED, "Path is inside a dependency or build directory.")
    if is_generated_path(path):
        return verdict(SourceStatus.GENERATED, "Path matches a generated-file or lockfile pattern.")

    # 4. Unsupported language — an explicit classification, never a guess.
    if language is None:
        return verdict(
            SourceStatus.UNSUPPORTED_LANGUAGE,
            f"No adapter for extension {_extension(path) or '(none)'}.",
        )

    # 5. No usable patch. Checked *after* language so the reason distinguishes
    #    "we could have parsed it but GitHub gave us no diff" from "we would
    #    not have parsed it anyway".
    if patch_status in (
        PatchStatus.ABSENT_TOO_LARGE,
        PatchStatus.ABSENT_UNKNOWN,
        PatchStatus.MALFORMED,
    ):
        return verdict(
            SourceStatus.NO_PATCH,
            f"No usable diff from GitHub ({patch_status.value}).",
        )

    # 6. Size ceilings.
    if declared_size_bytes is not None and declared_size_bytes > limits.max_file_bytes:
        return verdict(
            SourceStatus.TOO_LARGE,
            f"File exceeds the {limits.max_file_bytes}-byte limit.",
        )
    if changed_line_count > limits.max_changed_lines_per_file:
        return verdict(
            SourceStatus.TOO_LARGE,
            f"Changed lines exceed the {limits.max_changed_lines_per_file}-line limit.",
        )

    return verdict(SourceStatus.AVAILABLE)


