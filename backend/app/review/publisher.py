"""Publishing validated findings to GitHub.

This module is the only code in the platform that writes to a pull request,
and it accepts **only** ``ValidatedFinding``. The type signature is the
enforcement: there is no overload, no keyword argument and no escape hatch that
takes a ``RawFinding``. A test asserts that this module does not import one.

Four hazards shape the design.

**1. The head commit can move while we work.** A review takes tens of seconds;
a developer can push twice in that time. Comments anchored to a commit that is
no longer the head land on code the author has already replaced — the single
most damaging failure mode a review bot has, because it destroys trust
instantly. So the head SHA is re-read from GitHub immediately before
publication and compared against the SHA the findings were validated at. A
mismatch aborts publication entirely; it does not "publish anyway" or
"re-anchor".

**2. Review creation is atomic.** GitHub validates every inline comment and
rejects the *whole* review with 422 if any one of them is unpositionable — and
does not say which. A single bad comment would therefore lose every good one.
The salvage path handles that in two steps: retry with only the
highest-confidence subset, then fall back to a summary-only review that still
carries every finding as text. Findings are never silently dropped because
GitHub disliked one of them.

**3. A POST can succeed invisibly.** A timed-out create-review may already
have created the review. That is why ``AmbiguousWriteError`` exists and is not
retryable: the recovery is *reconciliation* — read GitHub's own comment list
and post only what is genuinely missing — not a blind retry.

**4. Republication must not duplicate.** Every comment body carries a hidden
marker containing the finding's fingerprint. Reconciliation matches on that
marker, so "have we already said this?" is answered by GitHub's own data
rather than by our assumption about what a previous attempt did.

**5. The model writes part of that body.** Hazard 4 makes the marker an
identity, and a validated finding still carries model-authored prose — title,
description, impact, suggested fix — verbatim into the same body. Model prose
containing a marker-shaped string is therefore a forged identity. See
``_sanitise_model_text`` and ``extract_marker``; this was a live defect until
Phase 6.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

from app.core.errors import (
    AmbiguousWriteError,
    GitHubValidationError,
    PermanentAccessError,
    ThrottledError,
    TransientError,
)
from app.core.logging import get_logger
from app.review.validator import ValidatedFinding

logger = get_logger(__name__)

MARKER_PREFIX = "codeguard-finding"
_MARKER_RE = re.compile(r"<!--\s*codeguard-finding:([0-9a-f]{8,64})\s*-->")

_SEVERITY_LABEL = {
    "critical": "🔴 Critical",
    "high": "🟠 High",
    "medium": "🟡 Medium",
    "low": "🔵 Low",
    "info": "⚪ Info",
}

_SEVERITY_RANK = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}

_DISCLAIMER = (
    "_Generated by CodeGuard AI. Findings are AI-generated and were "
    "mechanically verified against the diff; they still require human "
    "judgement._"
)


class PublishOutcome:
    """What publication achieved. Distinct from whether it raised."""

    PUBLISHED = "published"
    PUBLISHED_PARTIAL = "published_partial"
    SUMMARY_ONLY = "summary_only"
    NOTHING_TO_PUBLISH = "nothing_to_publish"
    SKIPPED_STALE_HEAD = "skipped_stale_head"
    SKIPPED_DISABLED = "skipped_disabled"
    FAILED = "failed"


@dataclass(frozen=True, slots=True)
class PostedComment:
    fingerprint: str
    path: str
    line: int
    side: str
    body_hash: str
    github_comment_id: int | None = None
    html_url: str | None = None


@dataclass(frozen=True, slots=True)
class PublishResult:
    outcome: str
    github_review_id: int | None = None
    posted: tuple[PostedComment, ...] = ()
    demoted: tuple[str, ...] = ()
    """Fingerprints that were demoted from inline to summary."""

    already_present: tuple[str, ...] = ()
    error: str | None = None
    observed_head_sha: str | None = None

    @property
    def succeeded(self) -> bool:
        return self.outcome in (
            PublishOutcome.PUBLISHED,
            PublishOutcome.PUBLISHED_PARTIAL,
            PublishOutcome.SUMMARY_ONLY,
            PublishOutcome.NOTHING_TO_PUBLISH,
        )

    def summary(self) -> dict[str, Any]:
        return {
            "outcome": self.outcome,
            "github_review_id": self.github_review_id,
            "posted": len(self.posted),
            "demoted": len(self.demoted),
            "already_present": len(self.already_present),
        }


# -- body rendering ----------------------------------------------------------


def finding_marker(fingerprint: str) -> str:
    """The hidden identity tag embedded in every comment body.

    An HTML comment, so GitHub renders nothing, and the fingerprint rather than
    a database id, so it stays meaningful across runs. This is what makes
    republication idempotent using GitHub's own state as the source of truth.
    """
    return f"<!-- {MARKER_PREFIX}:{fingerprint} -->"


def _sanitise_model_text(text: str) -> str:
    """Make model-authored prose safe to interpolate into a comment body.

    **Phase 6 fix (§13).** ``render_comment_body`` puts the model's own words
    into the same string as the finding marker. A model that emits

        <!-- codeguard-finding:<some other fingerprint> -->

    in its description — which prompt injection from the diff under review can
    cause, since the diff is attacker-controlled on a public repository — used
    to have that string published verbatim. The consequences were not cosmetic:

    * ``_existing_markers`` would record the *forged* fingerprint as present,
      so the genuine finding with that fingerprint is treated as already
      posted and is **silently suppressed on every subsequent run**. Model
      output would be deciding which real findings get published.
    * The comment's own fingerprint is never recorded, so it is re-posted on
      every run — the duplicate-suppression that hazard 4 exists to provide is
      inverted for exactly the comment that attacked it.
    * ``_reconcile_after_ambiguous_write`` reads the same markers to decide
      what a lost POST actually wrote, so the recorded outcome is wrong too.

    The delimiters are HTML-escaped rather than deleted. ``&lt;!--`` renders on
    GitHub as the literal text ``<!--``, so a reader still sees exactly what the
    model wrote — including that it tried this — while the parser no longer sees
    an HTML comment. Deleting the text would hide the attempt, and hiding it
    would remove the only evidence that it happened.

    No legitimate model text opens or closes an HTML comment: the marker is the
    only HTML comment a body is meant to contain, and we write it ourselves.

    Newlines in single-line fields are handled by ``_sanitise_model_line``
    below, not here; a description is genuinely multi-line.
    """
    return text.replace("<!--", "&lt;!--").replace("-->", "--&gt;")


def _sanitise_model_line(text: str) -> str:
    """As above, for a field rendered *inside* a line of Markdown.

    A title is put into a bold run on the comment's first line and into a
    bullet in the review summary. ``ValidatedFinding.title`` is stripped and
    truncated but keeps interior newlines, so a title of ``"Bug\\n\\n## Fake
    heading"`` used to break out of both and render as document structure.
    Collapsing whitespace is enough and is lossless in every legitimate case:
    a title is one line by definition.
    """
    return " ".join(_sanitise_model_text(text).split())


def extract_marker(body: str) -> str | None:
    """The finding fingerprint a comment body carries, or ``None``.

    Reads the **last** match, not the first. Our own marker is appended after
    everything else in ``render_comment_body``, so the last marker in a body is
    always ours; anything earlier was in text we did not write.
    ``_sanitise_model_text`` already prevents a forged marker from being
    published, and this makes the reader correct independently of it — the two
    fail in different ways, which is the point. It also keeps reconciliation
    correct for comments posted *before* that fix shipped.
    """
    matches = _MARKER_RE.findall(body or "")
    return matches[-1] if matches else None


def render_comment_body(finding: ValidatedFinding) -> str:
    """The inline comment text.

    Deliberately short. An inline comment competes with the code for attention,
    and a six-paragraph essay on a three-line function gets collapsed unread.
    The rationale and the full description live in the dashboard.
    """
    severity = _SEVERITY_LABEL.get(finding.severity.value, finding.severity.value)
    # Every model-authored field is sanitised on the way in. `severity`,
    # `category` and the marker are ours; `title`, `description`, `impact`,
    # `suggested_fix` and `cwe_id` are the model's. See `_sanitise_model_text`.
    parts = [
        f"**{severity} · {finding.category.value}** — {_sanitise_model_line(finding.title)}",
        "",
        _sanitise_model_text(finding.description),
    ]
    if finding.impact:
        parts.extend(["", f"**Impact:** {_sanitise_model_text(finding.impact)}"])
    if finding.suggested_fix:
        parts.extend(["", "**Suggested fix:**", "", _sanitise_model_text(finding.suggested_fix)])
    if finding.cwe_id:
        parts.extend(["", f"Reference: {_sanitise_model_line(finding.cwe_id)}"])
    if finding.anchor_relocated:
        # Stated rather than hidden. The model cited a different line and we
        # moved the comment; a reader who notices the discrepancy deserves to
        # know it was deliberate and verified, not a mistake.
        parts.extend(
            [
                "",
                f"<sub>Location resolved from the model's claim at line "
                f"{finding.claimed_line} by matching the quoted source.</sub>",
            ]
        )
    parts.extend(["", finding_marker(finding.fingerprint)])
    return "\n".join(parts)


def render_review_body(
    *,
    inline: Sequence[ValidatedFinding],
    summary_only: Sequence[ValidatedFinding],
    head_sha: str,
    run_id: str,
    model_name: str,
    rejected_count: int,
    context_truncated: bool = False,
    excluded_files: Sequence[str] = (),
) -> str:
    """The review's top-level body.

    **Always present, even with zero findings.** A tool that says nothing when
    it finds nothing is indistinguishable from a tool that is broken, and the
    difference matters to whoever has to decide whether to trust it.

    Findings that could not be anchored are listed here by name rather than
    discarded, so a developer sees them where they are working instead of only
    in a dashboard they may never open.
    """
    total = len(inline) + len(summary_only)
    counts: dict[str, int] = {}
    for finding in list(inline) + list(summary_only):
        counts[finding.severity.value] = counts.get(finding.severity.value, 0) + 1

    lines: list[str] = ["## CodeGuard AI review", ""]

    if total == 0:
        lines.append("✅ **No issues found** in the changed code.")
    else:
        breakdown = ", ".join(
            f"{counts[name]} {name}"
            for name in ("critical", "high", "medium", "low", "info")
            if counts.get(name)
        )
        lines.append(f"⚠️ **{total} finding{'s' if total != 1 else ''}** — {breakdown}.")

    if summary_only:
        lines.extend(
            [
                "",
                "### Findings without a verified inline location",
                "",
                "These were produced but could not be anchored to a line in "
                "this diff, so they are listed here rather than posted inline:",
                "",
            ]
        )
        for finding in sorted(
            summary_only, key=lambda f: (_SEVERITY_RANK.get(f.severity.value, 9), f.file_path)
        ):
            severity = _SEVERITY_LABEL.get(finding.severity.value, finding.severity.value)
            lines.append(
                f"- **{severity}** `{finding.file_path}` — {_sanitise_model_line(finding.title)}"
            )

    if rejected_count:
        lines.extend(
            [
                "",
                f"<sub>{rejected_count} further model suggestion"
                f"{'s' if rejected_count != 1 else ''} did not pass verification "
                "against the diff and were not published.</sub>",
            ]
        )

    if context_truncated:
        shown = ", ".join(f"`{path}`" for path in list(excluded_files)[:5])
        more = "" if len(excluded_files) <= 5 else f" and {len(excluded_files) - 5} more"
        lines.extend(
            [
                "",
                "<sub>⚠️ This pull request was larger than the review budget. "
                f"Some files were not reviewed{': ' + shown + more if shown else ''}.</sub>",
            ]
        )

    lines.extend(
        [
            "",
            "---",
            f"<sub>commit `{head_sha[:12]}` · model `{model_name}` · run `{run_id}`</sub>",
            "",
            _DISCLAIMER,
        ]
    )
    return "\n".join(lines)


def body_hash(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


# -- the publisher -----------------------------------------------------------


@dataclass(slots=True)
class ReviewPublisher:
    """Posts a validated review to one pull request."""

    client: Any
    installation_id: int
    owner: str
    repo: str
    pull_number: int
    max_inline_comments: int = 20
    publish_enabled: bool = True
    _marker_cache: dict[str, PostedComment] = field(default_factory=dict, repr=False)

    async def publish(
        self,
        *,
        findings: Sequence[ValidatedFinding],
        head_sha: str,
        run_id: str,
        model_name: str,
        rejected_count: int = 0,
        context_truncated: bool = False,
        excluded_files: Sequence[str] = (),
    ) -> PublishResult:
        """Publish, or explain precisely why nothing was published."""
        if not self.publish_enabled:
            # The kill switch. Analysis and persistence already happened; this
            # only stops the write to GitHub.
            return PublishResult(outcome=PublishOutcome.SKIPPED_DISABLED)

        # -- hazard 1: has the head moved? ---------------------------------
        observed = await self._observed_head_sha()
        if observed is not None and observed != head_sha:
            logger.warning(
                "review.publish.stale_head",
                expected_head=head_sha[:12],
                observed_head=observed[:12],
            )
            return PublishResult(
                outcome=PublishOutcome.SKIPPED_STALE_HEAD,
                observed_head_sha=observed,
                error="head commit moved during the review",
            )

        # -- hazard 4: what is already on the pull request? -----------------
        existing = await self._existing_markers()

        ranked = self._rank(findings)
        selected = [f for f in ranked[: self.max_inline_comments] if f.fingerprint not in existing]
        already_present = tuple(f.fingerprint for f in ranked if f.fingerprint in existing)
        overflow = [f for f in ranked[self.max_inline_comments :] if f.fingerprint not in existing]

        if not selected and not overflow:
            body = render_review_body(
                inline=(),
                summary_only=(),
                head_sha=head_sha,
                run_id=run_id,
                model_name=model_name,
                rejected_count=rejected_count,
                context_truncated=context_truncated,
                excluded_files=excluded_files,
            )
            if already_present:
                # Everything we would say is already said. Posting a second
                # review that repeats it is noise, so we stop here.
                return PublishResult(
                    outcome=PublishOutcome.NOTHING_TO_PUBLISH,
                    already_present=already_present,
                    observed_head_sha=observed,
                )
            review_id = await self._create(body=body, comments=[], head_sha=head_sha)
            return PublishResult(
                outcome=PublishOutcome.NOTHING_TO_PUBLISH,
                github_review_id=review_id,
                observed_head_sha=observed,
            )

        bodies = {f.fingerprint: render_comment_body(f) for f in selected}
        comments = [self._comment_payload(f, bodies[f.fingerprint]) for f in selected]
        review_body = render_review_body(
            inline=selected,
            summary_only=overflow,
            head_sha=head_sha,
            run_id=run_id,
            model_name=model_name,
            rejected_count=rejected_count,
            context_truncated=context_truncated,
            excluded_files=excluded_files,
        )

        # -- attempt 1: everything ------------------------------------------
        try:
            review_id = await self._create(body=review_body, comments=comments, head_sha=head_sha)
            return PublishResult(
                outcome=PublishOutcome.PUBLISHED,
                github_review_id=review_id,
                posted=self._posted(selected, bodies, review_id),
                demoted=tuple(f.fingerprint for f in overflow),
                already_present=already_present,
                observed_head_sha=observed,
            )
        except GitHubValidationError as exc:
            logger.warning("review.publish.422", comments=len(comments), detail=str(exc)[:200])
        except AmbiguousWriteError as exc:
            # -- hazard 3: the write may or may not have landed ------------
            return await self._reconcile_after_ambiguous_write(
                selected=selected,
                bodies=bodies,
                overflow=overflow,
                already_present=already_present,
                observed=observed,
                detail=str(exc)[:200],
            )
        except PermanentAccessError as exc:
            return PublishResult(
                outcome=PublishOutcome.FAILED,
                error=f"access lost: {exc}",
                observed_head_sha=observed,
            )
        except (TransientError, ThrottledError) as exc:
            # -- Phase 5 fix: a publication transient must NOT retry the review.
            #
            # Until Phase 5 these escaped ``publish()`` entirely. The runner
            # classified them retryable and rescheduled the *job* — but
            # ``persist_findings`` had already committed, so the retry created a
            # new ``review_run`` (attempt + 1) and inserted every finding again
            # under the new run id. The ON CONFLICT target is
            # ``(review_run_id, fingerprint)``, so a different run id is a
            # different row: the dashboard counted and displayed each finding
            # twice per retry.
            #
            # The correct outcome is the one the schema already has a word for.
            # The review *ran* and its findings are stored; publication did not
            # complete. That is ``partial_success`` — "Completed, partial" in
            # the UI, explicitly never "Passed" — and it is visible to the user
            # rather than silently re-run.
            #
            # Nothing is lost: the findings are in the database and on the
            # dashboard, and a re-review of the same commit reconciles against
            # the fingerprint markers already on the pull request, so a later
            # successful publication does not double-post.
            logger.warning(
                "review.publish.transient_giving_up",
                error_type=type(exc).__name__,
                detail=str(exc)[:200],
            )
            return PublishResult(
                outcome=PublishOutcome.FAILED,
                error=f"publication unavailable: {type(exc).__name__}",
                observed_head_sha=observed,
            )

        # -- hazard 2, salvage step 1: only added-line, high-confidence -----
        safer = [f for f in selected if f.confidence >= 0.75 and not f.anchor_relocated]
        if safer and len(safer) < len(selected):
            demoted_now = [f for f in selected if f not in safer]
            try:
                review_id = await self._create(
                    body=render_review_body(
                        inline=safer,
                        summary_only=list(overflow) + demoted_now,
                        head_sha=head_sha,
                        run_id=run_id,
                        model_name=model_name,
                        rejected_count=rejected_count,
                        context_truncated=context_truncated,
                        excluded_files=excluded_files,
                    ),
                    comments=[self._comment_payload(f, bodies[f.fingerprint]) for f in safer],
                    head_sha=head_sha,
                )
                return PublishResult(
                    outcome=PublishOutcome.PUBLISHED_PARTIAL,
                    github_review_id=review_id,
                    posted=self._posted(safer, bodies, review_id),
                    demoted=tuple(f.fingerprint for f in list(overflow) + demoted_now),
                    already_present=already_present,
                    observed_head_sha=observed,
                )
            except (GitHubValidationError, AmbiguousWriteError) as exc:
                logger.warning("review.publish.salvage_failed", detail=str(exc)[:200])

        # -- hazard 2, salvage step 2: summary only -------------------------
        # Every finding still reaches the developer, as text in the review
        # body. Losing them because GitHub would not accept a line number would
        # be the wrong trade.
        try:
            review_id = await self._create(
                body=render_review_body(
                    inline=(),
                    summary_only=list(selected) + list(overflow),
                    head_sha=head_sha,
                    run_id=run_id,
                    model_name=model_name,
                    rejected_count=rejected_count,
                    context_truncated=context_truncated,
                    excluded_files=excluded_files,
                ),
                comments=[],
                head_sha=head_sha,
            )
            return PublishResult(
                outcome=PublishOutcome.SUMMARY_ONLY,
                github_review_id=review_id,
                demoted=tuple(f.fingerprint for f in list(selected) + list(overflow)),
                already_present=already_present,
                observed_head_sha=observed,
            )
        except Exception as exc:
            logger.error("review.publish.failed", detail=str(exc)[:200])
            return PublishResult(
                outcome=PublishOutcome.FAILED,
                error=str(exc)[:200],
                demoted=tuple(f.fingerprint for f in list(selected) + list(overflow)),
                observed_head_sha=observed,
            )

    # -- internals ---------------------------------------------------------
    def _rank(self, findings: Sequence[ValidatedFinding]) -> list[ValidatedFinding]:
        """Severity first, then confidence, then a deterministic tie-break.

        Ranking decides which findings survive the inline-comment cap, so it
        must be total: two runs over the same findings must cut the same ones.
        """
        return sorted(
            findings,
            key=lambda f: (
                _SEVERITY_RANK.get(f.severity.value, 9),
                -f.confidence,
                f.file_path,
                f.line,
                f.fingerprint,
            ),
        )

    def _comment_payload(self, finding: ValidatedFinding, body: str) -> dict[str, Any]:
        """One inline comment.

        ``line`` + ``side``, never the deprecated ``position``. ``position`` is
        an offset into the diff text, which changes whenever the diff changes;
        ``line`` is a file line number and is what GitHub's current API
        documents (architecture.md §14.2).
        """
        return {
            "path": finding.file_path,
            "line": finding.line,
            "side": finding.side.value,
            "body": body,
        }

    async def _create(
        self, *, body: str, comments: list[dict[str, Any]], head_sha: str
    ) -> int | None:
        response = await self.client.create_pull_request_review(
            self.installation_id,
            self.owner,
            self.repo,
            self.pull_number,
            commit_id=head_sha,
            body=body,
            comments=comments,
        )
        review_id = response.get("id")
        return int(review_id) if isinstance(review_id, int) else None

    async def _observed_head_sha(self) -> str | None:
        """Read the pull request's current head SHA.

        Returns ``None`` when it cannot be determined. ``None`` means "we do not
        know", and the caller proceeds — refusing to publish because a
        preflight read failed would turn a transient GitHub hiccup into a lost
        review. A *known* mismatch is what aborts.
        """
        try:
            data = await self.client.get_json(
                self.installation_id,
                f"/repos/{self.owner}/{self.repo}/pulls/{self.pull_number}",
            )
        except Exception as exc:
            logger.warning("review.publish.preflight_failed", detail=str(exc)[:200])
            return None
        head = data.get("head")
        if isinstance(head, dict) and isinstance(head.get("sha"), str):
            return head["sha"]
        return None

    async def _existing_markers(self) -> dict[str, dict[str, Any]]:
        """Fingerprints already present as comments on this pull request."""
        try:
            comments = await self.client.list_review_comments(
                self.installation_id, self.owner, self.repo, self.pull_number
            )
        except Exception as exc:
            logger.warning("review.publish.list_comments_failed", detail=str(exc)[:200])
            return {}
        found: dict[str, dict[str, Any]] = {}
        for comment in comments:
            marker = extract_marker(comment.get("body", ""))
            if marker:
                found[marker] = comment
        return found

    async def _reconcile_after_ambiguous_write(
        self,
        *,
        selected: Sequence[ValidatedFinding],
        bodies: dict[str, str],
        overflow: Sequence[ValidatedFinding],
        already_present: tuple[str, ...],
        observed: str | None,
        detail: str,
    ) -> PublishResult:
        """Decide what the lost response actually did.

        The request timed out or the connection dropped. GitHub may have
        created the review, or may not have. Rather than guess, read the
        comment list again and see which of our markers are there. Whatever is
        present was posted; whatever is absent was not.
        """
        logger.warning("review.publish.ambiguous_write", detail=detail)
        after = await self._existing_markers()
        landed = [f for f in selected if f.fingerprint in after]
        missing = [f for f in selected if f.fingerprint not in after]

        if landed and not missing:
            return PublishResult(
                outcome=PublishOutcome.PUBLISHED,
                posted=self._posted(landed, bodies, None, github=after),
                demoted=tuple(f.fingerprint for f in overflow),
                already_present=already_present,
                observed_head_sha=observed,
            )
        if landed:
            # A partial landing. We do not post the remainder: a second review
            # attempt after an ambiguous one is how duplicates appear, and the
            # missing findings are already persisted and visible in the
            # dashboard.
            return PublishResult(
                outcome=PublishOutcome.PUBLISHED_PARTIAL,
                posted=self._posted(landed, bodies, None, github=after),
                demoted=tuple(f.fingerprint for f in list(missing) + list(overflow)),
                already_present=already_present,
                observed_head_sha=observed,
                error="publication outcome was ambiguous; reconciled against GitHub",
            )
        return PublishResult(
            outcome=PublishOutcome.FAILED,
            error="publication outcome was ambiguous and nothing was found on GitHub",
            demoted=tuple(f.fingerprint for f in list(selected) + list(overflow)),
            observed_head_sha=observed,
        )

    def _posted(
        self,
        findings: Sequence[ValidatedFinding],
        bodies: dict[str, str],
        review_id: int | None,
        github: dict[str, dict[str, Any]] | None = None,
    ) -> tuple[PostedComment, ...]:
        out = []
        for finding in findings:
            body = bodies.get(finding.fingerprint, "")
            remote = (github or {}).get(finding.fingerprint, {})
            comment_id = remote.get("id")
            out.append(
                PostedComment(
                    fingerprint=finding.fingerprint,
                    path=finding.file_path,
                    line=finding.line,
                    side=finding.side.value,
                    body_hash=body_hash(body),
                    github_comment_id=int(comment_id) if isinstance(comment_id, int) else None,
                    html_url=remote.get("html_url"),
                )
            )
        return tuple(out)


