"""Language detection and file classification.

Deterministic, content-free decisions made from the path alone — which is what
lets them run before a file is downloaded.
"""

from __future__ import annotations

import pytest
from app.analysis.diff.models import FileChangeType, PatchStatus
from app.analysis.source.classifier import (
    ClassificationLimits,
    classify,
    detect_language,
    has_generated_marker,
    is_generated_path,
    is_vendored,
)
from app.analysis.source.models import SourceStatus

LIMITS = ClassificationLimits(
    max_file_bytes=1_000_000, max_total_bytes=20_000_000, max_changed_lines_per_file=5_000
)


@pytest.mark.parametrize(
    ("path", "language"),
    [
        ("a.py", "python"),
        ("a.pyi", "python"),
        ("a.js", "javascript"),
        ("a.jsx", "javascript"),
        ("a.mjs", "javascript"),
        ("a.cjs", "javascript"),
        ("a.ts", "typescript"),
        ("a.tsx", "typescript"),
        ("a.java", "java"),
        ("deep/nested/path/Module.java", "java"),
        ("UPPER.PY", "python"),
    ],
)
def test_supported_extensions_are_detected(path: str, language: str) -> None:
    assert detect_language(path) == language


@pytest.mark.parametrize(
    "path", ["a.rb", "a.go", "a.rs", "a.c", "a.cpp", "Makefile", "README", "a", "a.unknown"]
)
def test_unsupported_extensions_return_none_rather_than_guessing(path: str) -> None:
    assert detect_language(path) is None


def test_declaration_files_are_not_typescript_source() -> None:
    """`.d.ts` is generated type surface, not code to review."""
    assert is_generated_path("types/index.d.ts")


@pytest.mark.parametrize(
    "path",
    [
        "node_modules/x/index.js",
        "vendor/lib/a.py",
        "a/dist/b.js",
        "target/classes/A.java",
        ".venv/lib/site-packages/x.py",
        "src/__pycache__/x.py",
    ],
)
def test_vendored_paths_are_detected(path: str) -> None:
    assert is_vendored(path)


@pytest.mark.parametrize(
    "path", ["src/my_vendor_utils.py", "src/distance.py", "src/building.ts", "src/outbox.py"]
)
def test_substring_lookalikes_are_not_treated_as_vendored(path: str) -> None:
    """Matching is on whole path components; `distance.py` is source code."""
    assert not is_vendored(path)


@pytest.mark.parametrize(
    "path",
    [
        "a.min.js",
        "styles.min.css",
        "proto/user_pb2.py",
        "api.pb.go",
        "package-lock.json",
        "yarn.lock",
        "poetry.lock",
        "types/x.d.ts",
        "__snapshots__/a.snap",
    ],
)
def test_generated_paths_are_detected(path: str) -> None:
    assert is_generated_path(path)


def test_generated_content_markers_are_detected() -> None:
    assert has_generated_marker("// Code generated by protoc. DO NOT EDIT.\nx")
    assert has_generated_marker("# @generated\nimport os")
    assert not has_generated_marker("import os\n\n# a normal file\n")


def test_marker_scan_only_reads_the_head_of_a_file() -> None:
    """A mention of 'do not edit' on line 400 is a comment, not a marker."""
    text = "\n".join(["import os"] * 400 + ["# do not edit"])
    assert not has_generated_marker(text)


def _classify(path: str, **kw):  # type: ignore[no-untyped-def]
    return classify(
        path=path,
        change_type=kw.pop("change_type", FileChangeType.MODIFIED),
        patch_status=kw.pop("patch_status", PatchStatus.PRESENT),
        changed_line_count=kw.pop("changed_line_count", 10),
        limits=kw.pop("limits", LIMITS),
        **kw,
    )


def test_a_normal_source_file_is_analysable() -> None:
    verdict = _classify("src/app.py")
    assert verdict.status is SourceStatus.AVAILABLE
    assert verdict.language == "python"
    assert verdict.should_fetch


def test_deleted_files_are_never_fetched() -> None:
    """Asking GitHub for the head version of a deleted file is a guaranteed 404."""
    verdict = _classify("src/gone.py", change_type=FileChangeType.DELETED)
    assert verdict.status is SourceStatus.DELETED
    assert not verdict.should_fetch


@pytest.mark.parametrize("path", ["logo.png", "app.jar", "lib.so", "font.woff2", "a.pyc"])
def test_binary_extensions_are_reported_as_binary(path: str) -> None:
    """Binary, not 'unsupported language' — the reason must be accurate."""
    assert _classify(path).status is SourceStatus.BINARY


def test_absent_binary_patch_is_reported_as_binary() -> None:
    assert (
        _classify("weird.py", patch_status=PatchStatus.ABSENT_BINARY).status is SourceStatus.BINARY
    )


def test_classification_order_is_most_specific_first() -> None:
    """A vendored binary reports as binary; a vendored .py as vendored."""
    assert _classify("node_modules/a/logo.png").status is SourceStatus.BINARY
    assert _classify("node_modules/a/index.js").status is SourceStatus.VENDORED


def test_unsupported_language_is_explicit_not_an_exception() -> None:
    verdict = _classify("src/main.go")
    assert verdict.status is SourceStatus.UNSUPPORTED_LANGUAGE
    assert verdict.reason and ".go" in verdict.reason


@pytest.mark.parametrize(
    "status", [PatchStatus.ABSENT_TOO_LARGE, PatchStatus.ABSENT_UNKNOWN, PatchStatus.MALFORMED]
)
def test_missing_patch_on_a_supported_file_is_its_own_reason(status: PatchStatus) -> None:
    """Distinct from 'unsupported': we could have parsed it, GitHub gave us nothing."""
    verdict = _classify("src/app.py", patch_status=status)
    assert verdict.status is SourceStatus.NO_PATCH
    assert verdict.language == "python"


def test_size_limits_are_configuration_not_magic_numbers() -> None:
    small = ClassificationLimits(
        max_file_bytes=100, max_total_bytes=1000, max_changed_lines_per_file=5
    )
    assert _classify("a.py", limits=small, declared_size_bytes=500).status is SourceStatus.TOO_LARGE
    assert _classify("a.py", limits=small, changed_line_count=50).status is SourceStatus.TOO_LARGE
    result = _classify("a.py", limits=small, declared_size_bytes=50, changed_line_count=2)
    assert result.status is SourceStatus.AVAILABLE


def test_every_skip_carries_a_reason() -> None:
    """ "Why wasn't my file reviewed?" must always have an answer."""
    for path, kwargs in [
        ("logo.png", {}),
        ("node_modules/a.js", {}),
        ("a.go", {}),
        ("gone.py", {"change_type": FileChangeType.DELETED}),
        ("a.py", {"patch_status": PatchStatus.ABSENT_UNKNOWN}),
    ]:
        verdict = _classify(path, **kwargs)
        assert verdict.status is not SourceStatus.AVAILABLE
        assert verdict.reason, f"{path} skipped with no reason"
